// Command gen-activitylog renders the activity-log reader schema (schema.go, the
// single field authority) into the checked-in reader-side Go sources: the
// private decode struct activityRawLine, the exported ActivityEntry, and the
// toEntry copier that bridges them.
//
// DRY: activity.jsonl, the --json StreamEvent wire, and this reader are three
// shapes for one datum. Before this generator the reader half repeated the flat
// field list three times (struct tags, exported fields, and hand-written copy
// code), guarded only by mechanical parity tests. Now the field list lives once
// in schema.go and the three reader artifacts are derived from it, so a new
// field cannot land on two of the three and drift.
//
// The output is drift-gated by scripts/docs/gate.sh activity-schema (wired into
// pre-commit + CI via `make docs-check`): editing schema.go without
// regenerating, or hand-editing the generated files, fails the gate until
// `make gen-activity-schema` is re-run and the result committed.
//
// Run: make gen-activity-schema  (or: go run ./scripts/gen/activitylog)
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// outDir is the destination directory for the generated files (the repo root by
// default). The drift gate overrides it via GEN_ACTIVITY_OUT to render to a temp
// dir and diff without clobbering the committed sources.
func outDir() string {
	if d := os.Getenv("GEN_ACTIVITY_OUT"); d != "" {
		return d
	}
	return "."
}

const (
	rawFile   = "tracker_activity_raw_gen.go"
	entryFile = "tracker_activity_entry_gen.go"
)

const genHeader = "// Code generated by scripts/gen/activitylog; DO NOT EDIT.\n" +
	"// Edit scripts/gen/activitylog/schema.go and run `make gen-activity-schema`.\n\n"

func main() {
	dir := outDir()
	if err := writeFormatted(filepath.Join(dir, rawFile), renderRaw()); err != nil {
		fatal(err)
	}
	if err := writeFormatted(filepath.Join(dir, entryFile), renderEntry()); err != nil {
		fatal(err)
	}
	fmt.Printf("gen-activitylog: wrote %s and %s (%d fields)\n", rawFile, entryFile, fieldCount())
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "gen-activitylog: %v\n", err)
	os.Exit(1)
}

// writeFormatted gofmt-canonicalizes src before writing so the committed output
// is byte-stable regardless of the raw template's spacing.
func writeFormatted(path, src string) error {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("format %s: %w\n---\n%s", path, err, src)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func fieldCount() int {
	n := 0
	for _, g := range schema {
		n += len(g.Fields)
	}
	return n
}

// blockComment renders text as a // comment block, one line per source line.
func blockComment(text string) string {
	var b strings.Builder
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		b.WriteString("// " + line + "\n")
	}
	return b.String()
}

// rawType is the decode-struct type for a field: the timestamp arrives as a
// string on the wire; everything else uses its ActivityEntry type verbatim.
func rawType(f field) string {
	if f.FromTS {
		return "string"
	}
	return f.Type
}

// renderRaw builds the source for activityRawLine and its toEntry copier.
func renderRaw() string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("package tracker\n\n")
	b.WriteString("import (\n\t\"time\"\n\n\t\"github.com/2389-research/tracker/pipeline\"\n)\n\n")

	b.WriteString(blockComment("activityRawLine is the wire-shaped decode target for one activity.jsonl\n" +
		"line. It is the read-side mirror of pipeline's private jsonlLogEntry:\n" +
		"every JSON name here is that writer's name, and every Go name is\n" +
		"ActivityEntry's (and StreamEvent's) Go name, so the three schemas cannot\n" +
		"drift apart — they are generated from one authority (scripts/gen/activitylog).\n" +
		"\n" +
		"Unknown keys are ignored by encoding/json, which is the documented\n" +
		"forward-compatibility contract: a newer runtime's extra field makes an\n" +
		"older reader lose that datum, never fail the line."))
	b.WriteString("type activityRawLine struct {\n")
	for i, g := range schema {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(indentComment(g.Comment))
		for _, f := range g.Fields {
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.Go, rawType(f), f.JSON)
		}
	}
	b.WriteString("}\n\n")

	b.WriteString(blockComment("toEntry builds the exported ActivityEntry from a decoded line. ts is\n" +
		"passed in already parsed because the timestamp needs dual-format handling\n" +
		"that keeps ActivityEntry off the JSON wire (see its doc comment).\n" +
		"\n" +
		"Aliasing: each ParseActivityLine call unmarshals into its own local\n" +
		"activityRawLine, so every map and slice below was freshly allocated by\n" +
		"encoding/json for this line only — no two entries can share backing\n" +
		"storage, and nothing in tracker retains r after this returns."))
	b.WriteString("func (r *activityRawLine) toEntry(ts time.Time) ActivityEntry {\n")
	b.WriteString("\tentry := ActivityEntry{}\n")
	for _, g := range schema {
		for _, f := range g.Fields {
			b.WriteString(copyStmt(f))
		}
	}
	b.WriteString("\treturn entry\n}\n")
	return b.String()
}

// copyStmt renders one field's copy in toEntry.
func copyStmt(f field) string {
	switch {
	case f.FromTS:
		return "\tentry.Timestamp = ts\n"
	case f.Defensive:
		// Defensive copy into fresh backing storage, guarded so a nil/empty
		// source stays nil (preserving the omitempty-equivalent zero value).
		return fmt.Sprintf("\tif len(r.%s) > 0 {\n\t\tentry.%s = append(%s(nil), r.%s...)\n\t}\n",
			f.Go, f.Go, f.Type, f.Go)
	default:
		return fmt.Sprintf("\tentry.%s = r.%s\n", f.Go, f.Go)
	}
}

// renderEntry builds the source for the exported ActivityEntry.
func renderEntry() string {
	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("package tracker\n\n")
	b.WriteString("import (\n\t\"time\"\n\n\t\"github.com/2389-research/tracker/pipeline\"\n)\n\n")

	b.WriteString(blockComment("ActivityEntry is a parsed line from activity.jsonl. Populate via\n" +
		"ParseActivityLine — ActivityEntry is not itself a JSON-wire type because\n" +
		"tracker has historically used two timestamp formats and time.Time's\n" +
		"default unmarshal handles only RFC3339Nano.\n" +
		"\n" +
		"Marshal/unmarshal contract: do not json.Marshal/json.Unmarshal\n" +
		"ActivityEntry directly. Use ParseActivityLine and LoadActivityLog for\n" +
		"decoding and map to your own wire type when encoding.\n" +
		"\n" +
		"Field contract: the reader is lossless — every field the runtime writes to\n" +
		"activity.jsonl is decoded here, and each field's Go name is the same as the\n" +
		"matching StreamEvent field (tracker_events.go), so replaying a finished run\n" +
		"from the audit log and following it live over NDJSON read the same names.\n" +
		"Every field except Timestamp is optional: a line carries only the fields\n" +
		"its event type emits, so a zero value means \"this line does not carry it\".\n" +
		"\n" +
		"Generated from scripts/gen/activitylog/schema.go, the single field\n" +
		"authority shared with activityRawLine and the toEntry copier."))
	b.WriteString("type ActivityEntry struct {\n")
	for i, g := range schema {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(indentComment(g.Comment))
		for _, f := range g.Fields {
			if f.Doc != "" {
				b.WriteString(indentComment(f.Doc))
			}
			fmt.Fprintf(&b, "\t%s %s\n", f.Go, f.Type)
		}
	}
	b.WriteString("}\n")
	return b.String()
}

// indentComment renders text as a tab-indented // comment block for use inside a
// struct declaration.
func indentComment(text string) string {
	var b strings.Builder
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			b.WriteString("\t//\n")
			continue
		}
		b.WriteString("\t// " + line + "\n")
	}
	return b.String()
}
